#!/bin/bash

EDP="newtonianSweep.edp"
LOG="runSweep.log"
echo "Inicio sweep: $(date)" | tee -a $LOG

run() {
    local wr=$1 rhoS=$2 vin=$3
    echo "--- wr=$wr rhoS=$rhoS vin=$vin ---" | tee -a $LOG
    FreeFem++ -v 0 $EDP -wr "$wr" -rhoS "$rhoS" -vin "$vin" 2>&1 | tee -a $LOG
    if [ ${PIPESTATUS[0]} -ne 0 ]; then
        echo "WARNING: fallo wr=$wr rhoS=$rhoS vin=$vin" | tee -a $LOG
    fi
}

# ── rhoS=1030, wr=0.044 ───────────────────────────────────────────────────────
for vin in 0.012 0.023 0.034 0.044 0.061 0.078 0.094 0.111 0.127 0.143 0.159; do
    run 0.044 1030 $vin
done

# ── rhoS=1030, wr=0.066 ───────────────────────────────────────────────────────
for vin in 0.012 0.023 0.034 0.044 0.061 0.078 0.094 0.111 0.127 0.143 0.159; do
    run 0.066 1030 $vin
done

# ── rhoS=1030, wr=0.033 ───────────────────────────────────────────────────────
for vin in 0.012 0.023 0.034 0.044 0.061 0.078 0.094 0.111 0.127 0.143 0.159; do
    run 0.033 1030 $vin
done

# ── vin=0.143, wr=0.044 ───────────────────────────────────────────────────────
for rhoS in 1067 1105 1145 1190 1235 1270 1325 1380 2000 3000; do
    run 0.044 $rhoS 0.143
done

# ── vin=0.143, wr=0.066 ───────────────────────────────────────────────────────
for rhoS in 1067 1105 1145 1190 1235 1270 1325 1380 2000 3000; do
    run 0.066 $rhoS 0.143
done

# ── vin=0.143, wr=0.033 ───────────────────────────────────────────────────────
for rhoS in 1067 1105 1145 1190 1235 1270 1325 1380 2000 3000; do
    run 0.033 $rhoS 0.143
done

# ── vin=0.111, wr=0.033 ───────────────────────────────────────────────────────
for rhoS in 1105 1270 1380; do
    run 0.033 $rhoS 0.111
done

# ── vin=0.078, wr=0.033 ───────────────────────────────────────────────────────
for rhoS in 1105 1270 1380; do
    run 0.033 $rhoS 0.078
done

# ── vin=0.044, wr=0.033 ───────────────────────────────────────────────────────
for rhoS in 1105 1270 1380; do
    run 0.033 $rhoS 0.044
done

# ── vin=0.023, wr=0.033 ───────────────────────────────────────────────────────
for rhoS in 1105 1270 1380; do
    run 0.033 $rhoS 0.023
done

echo "Sweep completo: $(date)" | tee -a $LOG